/**
 * Generate frame geometry for 3D printing
 */
export function generateFrameGeometry(
  settings: AnimationSequenceSettings,
  frame: FrameConfig
): THREE.Group {
  const frameGroup = new THREE.Group();
  frameGroup.name = `Frame_${frame.frameNumber}_${frame.frameName}`;
  
  // Base panel
  const panelGeometry = new THREE.BoxGeometry(
    settings.signWidth,
    settings.signHeight,
    2 // 2mm thick panel
  );
  
  const panelMesh = new THREE.Mesh(
    panelGeometry,
    new THREE.MeshStandardMaterial({ color: 0xFFFFFF })
  );
  frameGroup.add(panelMesh);
  
  // LED mounting channels based on pattern
  frame.ledPattern.forEach((ledIndex) => {
    const ledPosition = calculateLEDPosition(ledIndex, settings);
    const ledChannel = createLEDChannel();
    ledChannel.position.set(ledPosition.x, ledPosition.y, 1);
    frameGroup.add(ledChannel);
  });
  
  return frameGroup;
}

/**
 * Calculate LED position on panel
 */
function calculateLEDPosition(ledIndex: number, settings: AnimationSequenceSettings): Point2D {
  // Simple grid layout for now
  const ledsPerRow = Math.ceil(Math.sqrt(settings.ledCount));
  const row = Math.floor(ledIndex / ledsPerRow);
  const col = ledIndex % ledsPerRow;
  
  const spacingX = settings.signWidth / (ledsPerRow + 1);
  const spacingY = settings.signHeight / (ledsPerRow + 1);
  
  return {
    x: (col + 1) * spacingX - settings.signWidth / 2,
    y: (row + 1) * spacingY - settings.signHeight / 2,
  };
}

/**
 * Create LED mounting channel
 */
function createLEDChannel(): THREE.Mesh {
  const channelGeometry = new THREE.BoxGeometry(12, 3, 2);
  const channelMesh = new THREE.Mesh(
    channelGeometry,
    new THREE.MeshStandardMaterial({ color: 0x303030 })
  );
  return channelMesh;
}
