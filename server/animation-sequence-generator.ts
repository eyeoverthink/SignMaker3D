/**
 * Generate Arduino controller code for animation sequence
 */
export function generateAnimationControllerCode(settings: AnimationSequenceSettings): string {
  const controllerName = settings.controllerType.toUpperCase().replace('_', ' ');
  
  return `/*
 * ${settings.sequenceName} - Animation Controller
 * Generated by Sign-Sculptor Animation Sequence System
 * 
 * Controller: ${controllerName}
 * LED Type: ${settings.ledType.toUpperCase()}
 * Frame Count: ${settings.frameCount}
 * Animation Speed: ${settings.animationSpeed} FPS
 * Loop: ${settings.loopAnimation ? 'Yes' : 'No'}
 */

#include <FastLED.h>

// LED Configuration
#define LED_PIN ${settings.ledPin}
#define NUM_LEDS ${settings.ledCount}
#define LED_TYPE WS2812B
#define COLOR_ORDER GRB
#define BRIGHTNESS ${settings.brightnessLevels}

// Animation Configuration
#define FRAME_COUNT ${settings.frameCount}
#define FRAME_DELAY ${settings.frameDelay}
#define LOOP_ANIMATION ${settings.loopAnimation ? 'true' : 'false'}

${settings.includeDimmer ? `// Dimmer Configuration
#define DIMMER_PIN ${settings.dimmerPin}
int currentBrightness = BRIGHTNESS;
` : ''}

// LED Array
CRGB leds[NUM_LEDS];

// Current frame index
int currentFrame = 0;
unsigned long lastFrameTime = 0;

// Frame LED patterns (1 = ON, 0 = OFF)
const bool framePatterns[FRAME_COUNT][NUM_LEDS] = {
${settings.frames.map((frame, frameIndex) => {
  const pattern = Array(settings.ledCount).fill(false);
  frame.ledPattern.forEach(ledIndex => {
    if (ledIndex < settings.ledCount) pattern[ledIndex] = true;
  });
  return `  { ${pattern.map(p => p ? '1' : '0').join(', ')} }${frameIndex < settings.frameCount - 1 ? ',' : ''}`;
}).join('\n')}
};

// Frame colors (RGB)
const CRGB frameColors[FRAME_COUNT] = {
${settings.frames.map((frame, frameIndex) => 
  `  CRGB(${frame.color.r}, ${frame.color.g}, ${frame.color.b})${frameIndex < settings.frameCount - 1 ? ',' : ''}`
).join('\n')}
};

// Frame durations (ms)
const int frameDurations[FRAME_COUNT] = {
${settings.frames.map((frame, frameIndex) => 
  `  ${frame.duration}${frameIndex < settings.frameCount - 1 ? ',' : ''}`
).join('\n')}
};

void setup() {
  Serial.begin(115200);
  Serial.println("${settings.sequenceName} - Animation Starting");
  
  // Initialize FastLED
  FastLED.addLeds<LED_TYPE, LED_PIN, COLOR_ORDER>(leds, NUM_LEDS);
  FastLED.setBrightness(BRIGHTNESS);
  FastLED.clear();
  FastLED.show();
  
${settings.includeDimmer ? `  // Initialize dimmer pin
  pinMode(DIMMER_PIN, INPUT);
` : ''}
  
  Serial.println("Setup complete!");
}

void loop() {
  unsigned long currentTime = millis();
  
${settings.includeDimmer ? `  // Read dimmer value
  int dimmerValue = analogRead(DIMMER_PIN);
  currentBrightness = map(dimmerValue, 0, 1023, 10, 255);
  FastLED.setBrightness(currentBrightness);
` : ''}
  
  // Check if it's time to advance to next frame
  if (currentTime - lastFrameTime >= frameDurations[currentFrame]) {
    lastFrameTime = currentTime;
    
    // Display current frame
    displayFrame(currentFrame);
    
    // Advance to next frame
    currentFrame++;
    
    // Handle loop or stop
    if (currentFrame >= FRAME_COUNT) {
      if (LOOP_ANIMATION) {
        currentFrame = 0;
        Serial.println("Animation loop restart");
      } else {
        currentFrame = FRAME_COUNT - 1; // Stay on last frame
        Serial.println("Animation complete (no loop)");
      }
    }
    
    Serial.print("Frame: ");
    Serial.print(currentFrame + 1);
    Serial.print("/");
    Serial.println(FRAME_COUNT);
  }
}

void displayFrame(int frameIndex) {
  // Clear all LEDs
  FastLED.clear();
  
  // Set LEDs according to frame pattern
  for (int i = 0; i < NUM_LEDS; i++) {
    if (framePatterns[frameIndex][i]) {
      leds[i] = frameColors[frameIndex];
    }
  }
  
  // Update LED strip
  FastLED.show();
}

// Helper function to set all LEDs to a color (for testing)
void setAllLEDs(CRGB color) {
  for (int i = 0; i < NUM_LEDS; i++) {
    leds[i] = color;
  }
  FastLED.show();
}

// Helper function to test individual LEDs
void testLEDs() {
  Serial.println("Testing LEDs...");
  for (int i = 0; i < NUM_LEDS; i++) {
    FastLED.clear();
    leds[i] = CRGB::White;
    FastLED.show();
    delay(100);
    Serial.print("LED ");
    Serial.print(i);
    Serial.println(" ON");
  }
  FastLED.clear();
  FastLED.show();
  Serial.println("Test complete");
}
`;
}

