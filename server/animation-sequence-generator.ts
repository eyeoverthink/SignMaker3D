/**
 * ANIMATION SEQUENCE GENERATOR
 * Creates multi-frame LED animations with controller code generation
 * 
 * Features:
 * - Frame-based animation system (1-20 frames)
 * - Per-frame LED pattern control
 * - Arduino/ESP32 controller code generation
 * - Adjustable frame delay and animation speed
 * - Loop animation support
 * - PWM dimming control
 * 
 * Perfect for animated signs, moving figures, and interactive displays
 */

import * as THREE from "three";

interface Point2D {
  x: number;
  y: number;
}

/**
 * Animation Sequence Settings
 */
export interface AnimationSequenceSettings {
  // Sequence Configuration
  sequenceName: string;
  frameCount: number; // 1-20 frames
  frameDelay: number; // ms between frames
  animationSpeed: number; // FPS (frames per second)
  loopAnimation: boolean;
  
  // Frame Data
  frames: FrameConfig[];
  
  // LED Configuration
  ledType: "ws2812b" | "simple_led" | "neopixel";
  ledCount: number; // Total LEDs in system
  ledPin: number; // Data pin for addressable LEDs
  
  // Controller
  controllerType: "arduino_nano" | "esp32" | "xiao_samd21";
  includeDimmer: boolean;
  dimmerPin: number;
  brightnessLevels: number; // 1-255
  
  // Physical Dimensions
  signWidth: number; // mm
  signHeight: number; // mm
  
  // Export Options
  exportFormat: "stl" | "3mf";
  includeControllerCode: boolean;
  includeWiringDiagram: boolean;
}

/**
 * Individual Frame Configuration
 */
export interface FrameConfig {
  frameNumber: number;
  frameName: string;
  patternType: "stick_figure" | "text" | "shape" | "custom";
  ledPattern: number[]; // Array of LED indices that are ON for this frame
  brightness: number; // 0-255
  color: { r: number; g: number; b: number };
  duration: number; // ms to display this frame (overrides global frameDelay)
}

